// Command native-reference renders the shipped CLI, native OpenAPI documents,
// protobuf contracts and Hub authorization register without making a request.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/jonathanagustin/conduit/internal/conduitcli"
	"github.com/jonathanagustin/conduit/internal/hub/composition"
	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
	"go.yaml.in/yaml/v4"
)

var contracts = []string{
	"api/admin-status.json",
	"api/planning-sessions.yaml",
	"docs/operations/ontology-api.openapi.yaml",
	"docs/operations/packaging-runs.openapi.yaml",
}

const pages = "docs-site/src/content/docs/reference"

type operation struct {
	OperationID string         `json:"operationId" yaml:"operationId"`
	Summary     string         `json:"summary" yaml:"summary"`
	Description string         `json:"description" yaml:"description"`
	Parameters  []any          `json:"parameters" yaml:"parameters"`
	RequestBody any            `json:"requestBody" yaml:"requestBody"`
	Responses   map[string]any `json:"responses" yaml:"responses"`
}

type specification struct {
	OpenAPI string `json:"openapi" yaml:"openapi"`
	Info    struct {
		Title string `json:"title" yaml:"title"`
	} `json:"info" yaml:"info"`
	Paths      map[string]map[string]operation `json:"paths" yaml:"paths"`
	Components any                             `json:"components" yaml:"components"`
}

type coverage struct {
	Sources                 map[string]string `json:"sources"`
	RegisteredRoutes        int               `json:"registeredRoutes"`
	RoutesWithNativeOpenAPI int               `json:"routesWithNativeOpenAPI"`
	NativeOpenAPIOperations int               `json:"nativeOpenAPIOperations"`
	ProtoContracts          int               `json:"protoContracts"`
	CLICommands             int               `json:"cliCommands"`
}

func main() {
	write := flag.Bool("write", false, "write reviewed generated reference pages")
	flag.Parse()
	if err := generate(*write); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(write bool) error {
	if _, err := os.Stat("go.mod"); err != nil {
		return fmt.Errorf("run from the Conduit repository root")
	}
	outputs := map[string][]byte{}
	stats := coverage{Sources: map[string]string{}}
	read := func(path string) ([]byte, error) {
		body, err := os.ReadFile(path)
		if err == nil {
			sum := sha256.Sum256(body)
			stats.Sources[path] = hex.EncodeToString(sum[:])
		}
		return body, err
	}
	known := map[string]string{}
	var api strings.Builder
	api.WriteString(front("Native API contracts", "Generated operations and schemas from the native OpenAPI contracts, with their exact coverage boundary."))
	api.WriteString("Generated by `go run ./tools/native-reference --write`. These are the complete committed native OpenAPI documents, not a claim that every Hub route has a typed schema. Missing contracts remain tracked in [#391](https://github.com/jonathanagustin/conduit/issues/391); handler and client work is tracked in #392–#394. Approval and execution authority still come from the Hub.\n\n")
	for _, path := range contracts {
		body, err := read(path)
		if err != nil {
			return err
		}
		var spec specification
		if err := yaml.Unmarshal(body, &spec); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		if spec.OpenAPI == "" || len(spec.Paths) == 0 {
			return fmt.Errorf("%s has no OpenAPI operations", path)
		}
		fmt.Fprintf(&api, "## %s\n\nSource: [%s](%s).\n\n", text(spec.Info.Title), path, repoLink(path))
		for _, endpoint := range sortedKeys(spec.Paths) {
			for _, method := range sortedKeys(spec.Paths[endpoint]) {
				if !isMethod(method) {
					continue
				}
				op := spec.Paths[endpoint][method]
				if op.OperationID == "" {
					return fmt.Errorf("%s %s has no operationId", method, endpoint)
				}
				key := strings.ToUpper(method) + " " + endpoint
				if previous := known[normalize(key)]; previous != "" {
					return fmt.Errorf("duplicate native contract operation %s", key)
				}
				known[normalize(key)] = path
				stats.NativeOpenAPIOperations++
				fmt.Fprintf(&api, "### %s\n\nOperation: `%s`. %s\n\n", text(key), text(op.OperationID), text(op.Summary))
				if op.Description != "" {
					fmt.Fprintf(&api, "%s\n\n", text(op.Description))
				}
				encoded, err := json.MarshalIndent(op, "", "  ")
				if err != nil {
					return err
				}
				fmt.Fprintf(&api, "```json\n%s\n```\n\n", encoded)
			}
		}
		var full any
		if err := yaml.Unmarshal(body, &full); err != nil {
			return err
		}
		components, err := json.MarshalIndent(full, "", "  ")
		if err != nil {
			return err
		}
		fmt.Fprintf(&api, "### Complete source contract\n\nThe normalized source below preserves shared schemas, parameters, security and every other top-level or operation field.\n\n```json\n%s\n```\n\n", components)
	}
	outputs[pages+"/native-api.md"] = []byte(api.String())

	var routes strings.Builder
	routes.WriteString(front("Hub route coverage", "The shipped route and authorization register, including explicit native contract gaps."))
	routes.WriteString("Generated from `internal/hub/composition/authorization.go`; this is a route and access-decision inventory, not a substitute for request/response schemas. Compatibility adapter paths are listed by their shipped names; this does not claim a private upstream protocol. The [native API reference](/conduit/reference/native-api/) renders the available schemas. [#391](https://github.com/jonathanagustin/conduit/issues/391) owns the uncontracted remainder.\n\n")
	if _, err := read("internal/hub/composition/authorization.go"); err != nil {
		return err
	}
	entries := composition.HubRouteAuthorization()
	sort.Slice(entries, func(i, j int) bool { return entries[i].Pattern < entries[j].Pattern })
	stats.RegisteredRoutes = len(entries)
	var table strings.Builder
	table.WriteString("| Registered route | Access decision | Native OpenAPI contract |\n| --- | --- | --- |\n")
	for _, route := range entries {
		source := known[normalize(route.Pattern)]
		label := "No native schema"
		if source != "" {
			stats.RoutesWithNativeOpenAPI++
			label = fmt.Sprintf("[%s](%s)", source, repoLink(source))
		}
		fmt.Fprintf(&table, "| `%s` | `%s` | %s |\n", text(route.Pattern), route.Decision, label)
	}
	fmt.Fprintf(&routes, "%d registered patterns; %d match a native OpenAPI operation. These counts are generated, and include method-not-allowed fallback patterns. Protobuf methods are documented separately and are not counted as additional REST schemas.\n\n", stats.RegisteredRoutes, stats.RoutesWithNativeOpenAPI)
	routes.WriteString(table.String())
	outputs[pages+"/route-coverage.md"] = []byte(routes.String())

	protoFiles, err := filepath.Glob("proto/conduit/*/v1/*.proto")
	if err != nil {
		return err
	}
	if len(protoFiles) == 0 {
		return fmt.Errorf("no native protobuf contracts found")
	}
	var proto strings.Builder
	proto.WriteString(front("Typed RPC contracts", "The exact native protobuf messages and service methods currently committed."))
	proto.WriteString("Generated from the native `.proto` files. Each source below defines only its declared methods. REST remains available during the staged migration; no automatic fallback or replay of an ambiguous write is authorized by these contracts. Transport implementation and browser adoption remain tracked separately in #392–#394.\n\n")
	for _, path := range protoFiles {
		body, err := read(path)
		if err != nil {
			return err
		}
		stats.ProtoContracts++
		fmt.Fprintf(&proto, "## %s\n\n[%s](%s)\n\n```protobuf\n%s\n```\n\n", text(filepath.Base(path)), path, repoLink(path), strings.TrimSpace(string(body)))
	}
	outputs[pages+"/rpc.md"] = []byte(proto.String())

	cli := conduitcli.NewRoot(conduitcli.Runtime{Stdin: strings.NewReader(""), Stdout: io.Discard, Stderr: io.Discard, Getenv: func(string) string { return "" }})
	var commands strings.Builder
	commands.WriteString(front("CLI command reference", "Generated from the native conduit command tree, including arguments and flags."))
	commands.WriteString("Generated from `conduitcli.NewRoot` with an empty configuration environment. No command is executed and no credential is read. Defaults below are parser defaults, not deployment configuration. A command's presence does not promise that its backing service is configured: explicit unsupported and unavailable responses remain authoritative. See [Using the CLI](/conduit/cli/) before running a mutation.\n\n## Connection and output flags\n\n")
	flags(&commands, cli.PersistentFlags())
	var walk func(*cobra.Command)
	walk = func(command *cobra.Command) {
		if command.Hidden {
			return
		}
		stats.CLICommands++
		fmt.Fprintf(&commands, "## %s\n\n%s\n\n```text\n%s\n```\n\n", text(command.CommandPath()), text(command.Short), command.UseLine())
		flags(&commands, command.LocalNonPersistentFlags())
		for _, child := range command.Commands() {
			walk(child)
		}
	}
	walk(cli)
	outputs[pages+"/cli-commands.md"] = []byte(commands.String())
	cliSources, err := filepath.Glob("internal/conduitcli/*.go")
	if err != nil {
		return err
	}
	for _, path := range cliSources {
		if !strings.HasSuffix(path, "_test.go") {
			if _, err := read(path); err != nil {
				return err
			}
		}
	}
	data, err := json.MarshalIndent(stats, "", "  ")
	if err != nil {
		return err
	}
	outputs["docs/operations/native-reference-coverage.json"] = append(data, '\n')
	for _, path := range sortedKeys(outputs) {
		if write {
			if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
				return err
			}
			if err := os.WriteFile(path, outputs[path], 0644); err != nil {
				return err
			}
		} else {
			existing, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(existing, outputs[path]) {
				return fmt.Errorf("generated reference is stale: %s; run go run ./tools/native-reference --write", path)
			}
		}
	}
	fmt.Printf("PASS native reference: %d CLI commands, %d native OpenAPI operations, %d protobuf sources; %d/%d registered routes have native OpenAPI\n", stats.CLICommands, stats.NativeOpenAPIOperations, stats.ProtoContracts, stats.RoutesWithNativeOpenAPI, stats.RegisteredRoutes)
	return nil
}

func flags(out *strings.Builder, set *pflag.FlagSet) {
	if set.NFlag() == 0 && !set.HasAvailableFlags() {
		return
	}
	out.WriteString("| Flag | Type | Default | Meaning |\n| --- | --- | --- | --- |\n")
	set.VisitAll(func(flag *pflag.Flag) {
		if !flag.Hidden {
			fmt.Fprintf(out, "| `--%s` | `%s` | `%s` | %s |\n", flag.Name, flag.Value.Type(), text(flag.DefValue), text(flag.Usage))
		}
	})
	out.WriteString("\n")
}

func front(title, description string) string {
	return fmt.Sprintf("---\ntitle: %s\ndescription: %s\n---\n\n", title, description)
}
func repoLink(path string) string {
	return "https://github.com/jonathanagustin/conduit/blob/main/" + path
}
func text(value string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", "|", "\\|", "`", "\\`", "\r", " ", "\n", " ").Replace(value)
}

var parameter = regexp.MustCompile(`\{[^}]+\}`)

func normalize(value string) string { return parameter.ReplaceAllString(value, "{}") }
func isMethod(method string) bool {
	return strings.Contains(" get post put patch delete head options ", " "+method+" ")
}
func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
