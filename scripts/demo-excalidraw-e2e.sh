#!/usr/bin/env bash
# End-to-end Excalidraw AI Packaging Demo across CLI and Hub + Operator Console Frontend.
# Demonstrates:
# 1. Real executable agent (`packaging-workflow agent-exec` via CONDUIT_MODEL_CMD)
#    executing multi-round tool calls (`inspect_repo`, `read_file`), eliciting NeedsInput
#    (`node_version`), synthesizing a canonical Excalidraw packaging plan, and generating
#    non-root digest-pinned Dockerfile + zarf.yaml + uds-package.yaml (`uds.dev/v1alpha1` Package CR).
# 2. Full CLI flow (`plan-create`, `plan-turn`, `plan-answer`, `plan-turn`, `plan-accept`,
#    `plan-compute`, `mcp-serve`, `workspace-tree`, `workspace-file`, `workspace-diff`,
#    `workspace-propose`).
# 3. Full Hub + Frontend flow (Temporal-backed `/v1/planning-sessions`, `/v1/agent-runs` SSE,
#    Operator Console browser automation via Playwright from Work Intake -> Agent SSE Turn ->
#    NeedsInput -> Plan Review -> Accept -> Package into Git Workspace, `/v1/dev-workspaces`
#    file/tree inspection, and Hub-mediated ACP coding-agent session).
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT_DIR}"

if [[ -d "/tmp/pinned-bin" ]]; then
  export PATH="/tmp/pinned-bin:${PATH}"
  if [[ -x "/tmp/pinned-bin/zarf" ]]; then
    export ZARF_BIN="/tmp/pinned-bin/zarf"
  fi
fi

TEMPORAL_CLI="${CONDUIT_TEMPORAL_CLI:-${ROOT_DIR}/.cache/temporal/temporal}"
if [[ ! -x "${TEMPORAL_CLI}" ]]; then
  echo "Fetching Temporal CLI..."
  ./scripts/fetch-temporal-cli.sh
fi
export CONDUIT_TEMPORAL_CLI="${TEMPORAL_CLI}"

DEMO_TMP="$(mktemp -d -t conduit-excalidraw-e2e-XXXXXX)"
PIDS=()
cleanup() {
  for pid in "${PIDS[@]:-}"; do
    if [[ -n "${pid}" ]] && kill -0 "${pid}" 2>/dev/null; then
      kill "${pid}" 2>/dev/null || true
      wait "${pid}" 2>/dev/null || true
    fi
  done
  rm -rf "${DEMO_TMP}"
}
trap cleanup EXIT

echo "==> [1/6] Building packaging-workflow and platform-delivery binaries..."
BIN_DIR="${DEMO_TMP}/bin"
mkdir -p "${BIN_DIR}"
go build -o "${BIN_DIR}/packaging-workflow" ./cmd/packaging-workflow
go build -o "${BIN_DIR}/platform-delivery" ./cmd/platform-delivery

export CONDUIT_MODEL_CMD="${BIN_DIR}/packaging-workflow agent-exec"
echo "    CONDUIT_MODEL_CMD=${CONDUIT_MODEL_CMD}"

# Prepare local Excalidraw source repository to bootstrap
EXCALIDRAW_SRC="${DEMO_TMP}/excalidraw-src"
mkdir -p "${EXCALIDRAW_SRC}"
cat > "${EXCALIDRAW_SRC}/package.json" <<'EOF'
{
  "name": "excalidraw",
  "version": "0.17.6",
  "description": "Virtual whiteboard for sketching hand-drawn like diagrams",
  "scripts": {
    "start": "yarn start",
    "build:app:docker": "yarn build"
  },
  "dependencies": {
    "react": "^18.2.0",
    "react-dom": "^18.2.0"
  }
}
EOF
cat > "${EXCALIDRAW_SRC}/yarn.lock" <<'EOF'
# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1
EOF
cat > "${EXCALIDRAW_SRC}/tsconfig.json" <<'EOF'
{
  "compilerOptions": {
    "strict": true,
    "target": "ES2022"
  }
}
EOF
cat > "${EXCALIDRAW_SRC}/README.md" <<'EOF'
# Excalidraw
Collaborative virtual whiteboard packaged with Conduit, Zarf, and Defense Unicorns UDS.
EOF
export CONDUIT_DEMO_SOURCE_DIR="${EXCALIDRAW_SRC}"

echo "==> [2/6] Starting Temporal devserver and packaging-workflow worker..."
STATE_DIR="${DEMO_TMP}/state"
export DEVWORKSPACE_GIT_ROOT="${STATE_DIR}/workspaces"
mkdir -p "${STATE_DIR}"

SERVER_LOG="${DEMO_TMP}/temporal-server.log"
"${BIN_DIR}/packaging-workflow" --cli "${CONDUIT_TEMPORAL_CLI}" --db "${DEMO_TMP}/temporal.db" start-server >"${SERVER_LOG}" 2>&1 &
PIDS+=("$!")

TEMPORAL_ADDR=""
for _ in $(seq 1 60); do
  if grep -q "frontend " "${SERVER_LOG}" 2>/dev/null; then
    TEMPORAL_ADDR="$(awk '/frontend /{print $2; exit}' "${SERVER_LOG}")"
    break
  fi
  sleep 0.25
done
if [[ -z "${TEMPORAL_ADDR}" ]]; then
  echo "Failed to start Temporal devserver:" >&2
  cat "${SERVER_LOG}" >&2
  exit 1
fi
echo "    Temporal frontend listening at ${TEMPORAL_ADDR}"

WORKER_LOG="${DEMO_TMP}/worker.log"
"${BIN_DIR}/packaging-workflow" --address "${TEMPORAL_ADDR}" --state-dir "${STATE_DIR}" worker --plan-fixture=false >"${WORKER_LOG}" 2>&1 &
PIDS+=("$!")
sleep 1

echo "==> [3/6] Running End-to-End CLI Packaging Flow with Real Agent (CONDUIT_MODEL_CMD)..."
PW_CLI=("${BIN_DIR}/packaging-workflow" --address "${TEMPORAL_ADDR}" --state-dir "${STATE_DIR}")

CREATE_JSON="$("${PW_CLI[@]}" plan-create "${EXCALIDRAW_SRC}" main --session-id ps_cli_demo --actor alice --local-only)"
echo "    plan-create status: $(echo "${CREATE_JSON}" | jq -r '.status') (repoUrl=$(echo "${CREATE_JSON}" | jq -r '.intake.repoUrl'))"

TURN1_JSON="$("${PW_CLI[@]}" plan-turn ps_cli_demo "Inspect Excalidraw repository and identify runtime needs" --actor alice)"
echo "    plan-turn 1 status: $(echo "${TURN1_JSON}" | jq -r '.status'), model: $(echo "${TURN1_JSON}" | jq -r '.model'), toolCalls: $(echo "${TURN1_JSON}" | jq -c '.inspection.toolCalls'), question: $(echo "${TURN1_JSON}" | jq -r '.needsInput[0].id')"
test "$(echo "${TURN1_JSON}" | jq -r '.status')" = "needs_input"
test "$(echo "${TURN1_JSON}" | jq -r '.model')" = "conduit-packaging-agent-v1"

ANS_JSON="$("${PW_CLI[@]}" plan-answer ps_cli_demo "node_version=20" --actor alice)"
echo "    plan-answer status: $(echo "${ANS_JSON}" | jq -r '.status')"

TURN2_JSON="$("${PW_CLI[@]}" plan-turn ps_cli_demo "Write the Excalidraw Zarf and UDS packaging plan for Node 20" --actor alice)"
echo "    plan-turn 2 status: $(echo "${TURN2_JSON}" | jq -r '.status'), plan sha256: $(echo "${TURN2_JSON}" | jq -r '.plan.sha256')"
test "$(echo "${TURN2_JSON}" | jq -r '.status')" = "ready"

ACCEPT_JSON="$("${PW_CLI[@]}" plan-accept ps_cli_demo --actor alice)"
echo "    plan-accept status: $(echo "${ACCEPT_JSON}" | jq -r '.status'), resolvedCommit: $(echo "${ACCEPT_JSON}" | jq -r '.binding.resolvedCommit')"
test "$(echo "${ACCEPT_JSON}" | jq -r '.status')" = "accepted"

COMPUTE_JSON="$("${PW_CLI[@]}" plan-compute ps_cli_demo --actor alice --workspace-id wsp_ps_cli_demo)"
echo "    plan-compute outcome: $(echo "${COMPUTE_JSON}" | jq -r '.result.outcome'), adapter: $(echo "${COMPUTE_JSON}" | jq -r '.result.provenance.adapter'), archive: $(echo "${COMPUTE_JSON}" | jq -r '.result.archive')"
test "$(echo "${COMPUTE_JSON}" | jq -r '.result.outcome')" = "PASS"

MCP_TOOLS="$("${PW_CLI[@]}" mcp-serve --workspace-id wsp_ps_cli_demo --list-tools)"
echo "    mcp-serve tools count: $(echo "${MCP_TOOLS}" | jq '.tools | length')"
MCP_INSPECT="$("${PW_CLI[@]}" mcp-serve --workspace-id wsp_ps_cli_demo --call inspect_repo)"
HAS_DOCKERFILE="$(echo "${MCP_INSPECT}" | jq -r '.structuredContent.hasDockerfile // (.content[0].text | fromjson | .hasDockerfile)')"
echo "    mcp-serve inspect_repo hasDockerfile: ${HAS_DOCKERFILE}"
test "${HAS_DOCKERFILE}" = "true"

PROPOSE_JSON="$("${PW_CLI[@]}" workspace-propose wsp_ps_cli_demo --actor alice --title "Onboard Excalidraw UDS/Zarf package")"
CR_ID="$(echo "${PROPOSE_JSON}" | jq -r '.ChangeRequestID // .changeRequestId')"
CR_STATUS="$(echo "${PROPOSE_JSON}" | jq -r '.Status // .status')"
echo "    workspace-propose changeRequestId: ${CR_ID} (${CR_STATUS})"
[[ "${CR_STATUS}" == PENDING* ]]

echo "==> [4/6] Starting Conduit Hub (platform-delivery) connected to Temporal & gitstore..."
HUB_PORT="$(python3 -c 'import socket; s=socket.socket(); s.bind(("127.0.0.1", 0)); print(s.getsockname()[1]); s.close()')"
HUB_URL="http://127.0.0.1:${HUB_PORT}"
HUB_LOG="${DEMO_TMP}/hub.log"

CONDUIT_TEMPORAL_ADDRESS="${TEMPORAL_ADDR}" \
CONDUIT_MODEL_CMD="${CONDUIT_MODEL_CMD}" \
DEVWORKSPACE_GIT_ROOT="${DEVWORKSPACE_GIT_ROOT}" \
CONDUIT_DEMO_SOURCE_DIR="${EXCALIDRAW_SRC}" \
LISTEN_ADDRESS="127.0.0.1:${HUB_PORT}" \
ALLOW_INSECURE_AGENT_IDENTITY_HEADERS="true" \
ALLOW_INSECURE_OPERATOR_IDENTITY_HEADERS="true" \
ALLOW_INSECURE_EPHEMERAL_BUNDLE_SIGNING_KEY="true" \
PLATFORM_BOOTSTRAP_ADMINISTRATORS="alice,operator" \
"${BIN_DIR}/platform-delivery" >"${HUB_LOG}" 2>&1 &
PIDS+=("$!")

export NO_PROXY="127.0.0.1,localhost"
export no_proxy="127.0.0.1,localhost"

HUB_READY=0
for _ in $(seq 1 40); do
  if curl --noproxy '*' -fsS -H "X-Platform-Subject: alice" "${HUB_URL}/v1/planning-sessions" -X POST -H "Content-Type: application/json" -d '{"repoUrl":"https://github.com/org/probe","ref":"main"}' >/dev/null 2>&1; then
    HUB_READY=1
    break
  fi
  sleep 0.25
done
if [[ "${HUB_READY}" -ne 1 ]]; then
  echo "Failed to start Hub:" >&2
  cat "${HUB_LOG}" >&2
  exit 1
fi
echo "    Hub listening at ${HUB_URL}"

echo "==> [5/6] Driving Operator Console Frontend end-to-end via Playwright with Real Agent (recording 1080p video)..."
SCREENSHOT_DIR="${CONDUIT_DEMO_SCREENSHOT_DIR:-${DEMO_TMP}/screenshots}"
mkdir -p "${SCREENSHOT_DIR}"
RAW_VIDEO_DIR="${DEMO_TMP}/raw-video"
mkdir -p "${RAW_VIDEO_DIR}"

if command -v ffmpeg >/dev/null 2>&1 && [[ ! -x "${HOME}/.cache/ms-playwright/ffmpeg-1013/ffmpeg-linux" ]]; then
  mkdir -p "${HOME}/.cache/ms-playwright/ffmpeg-1013"
  ln -sf "$(command -v ffmpeg)" "${HOME}/.cache/ms-playwright/ffmpeg-1013/ffmpeg-linux"
fi

HTTP_PROXY="" HTTPS_PROXY="" http_proxy="" https_proxy="" \
HUB_URL="${HUB_URL}" SCREENSHOT_DIR="${SCREENSHOT_DIR}" RAW_VIDEO_DIR="${RAW_VIDEO_DIR}" node --input-type=module - <<'EOF'
import { chromium } from "./web/node_modules/@playwright/test/index.mjs";

const hubUrl = process.env.HUB_URL;
const screenshotDir = process.env.SCREENSHOT_DIR;
const rawVideoDir = process.env.RAW_VIDEO_DIR;

const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({
    viewport: { width: 1920, height: 1080 },
    colorScheme: "dark",
    recordVideo: {
      dir: rawVideoDir,
      size: { width: 1920, height: 1080 },
    },
    extraHTTPHeaders: {
      "X-Platform-Subject": "alice",
      "X-Platform-Roles": "platform-admin",
    },
  });
  const page = await context.newPage();

  // Ensure Obsidian Theme is locked in localStorage before loading
  await page.addInitScript(() => {
    try {
      localStorage.setItem("conduit.console.prefs.v1", JSON.stringify({ theme: "dark", density: "comfortable" }));
      document.documentElement.dataset.theme = "dark";
    } catch {}
  });

  // Start on Obsidian Fleet Command Center briefly, then transition to Work Intake (#s01-intake)
  await page.goto(`${hubUrl}/console/`, { waitUntil: "networkidle" });
  await page.waitForTimeout(1200);

  await page.goto(`${hubUrl}/console/#s01-intake`, { waitUntil: "networkidle" });
  await page.waitForSelector("[data-plan-composer]");
  await page.waitForTimeout(900);

  // 1. Fill Excalidraw repository intake + Turn 1 prompt -> Real agent calls inspect_repo & read_file and elicits NeedsInput (node_version)
  await page.fill("#plan-repo", "https://github.com/excalidraw/excalidraw");
  await page.waitForTimeout(300);
  await page.fill("#plan-ref", "main");
  await page.waitForTimeout(300);
  await page.fill("#plan-message", "Inspect Excalidraw and prepare Zarf + Defense Unicorns UDS packaging");
  await page.waitForTimeout(700);
  await page.click("[data-plan-send]");

  await page.waitForSelector("[data-plan-needs-input]", { timeout: 25000 });
  await page.waitForSelector('[data-plan-answer="node_version"]', { timeout: 25000 });
  await page.waitForTimeout(1400);
  await page.screenshot({ path: `${screenshotDir}/e2e-1-needs-input.png`, fullPage: false });
  console.log("    [Browser] Captured NeedsInput (node_version) & inspection tool calls");

  // 2. Select Node 20 and submit answers -> Real agent synthesizes Ready plan
  await page.selectOption('[data-plan-answer="node_version"]', "20");
  await page.waitForTimeout(800);
  await page.click("[data-plan-submit-answers]");

  await page.waitForSelector("[data-plan-review]", { timeout: 25000 });
  await page.waitForSelector("[data-plan-accept]:not([disabled])", { timeout: 25000 });
  await page.waitForTimeout(1400);
  await page.screenshot({ path: `${screenshotDir}/e2e-2-plan-ready.png`, fullPage: false });
  console.log("    [Browser] Captured Plan Ready review");

  // Toggle View JSON briefly to showcase canonical JSON plan
  if (await page.locator("[data-plan-view-json]").count()) {
    await page.click("[data-plan-view-json]");
    await page.waitForTimeout(1200);
    await page.click("[data-plan-view-json]");
    await page.waitForTimeout(700);
  }

  // 3. Click Accept -> Commits governance audit receipt & renders Accepted Binding
  await page.click("[data-plan-accept]");
  await page.waitForSelector("[data-plan-binding]", { timeout: 25000 });
  await page.waitForSelector("[data-plan-compute]", { timeout: 25000 });
  await page.waitForTimeout(1300);
  await page.screenshot({ path: `${screenshotDir}/e2e-3-plan-accepted.png`, fullPage: false });
  console.log("    [Browser] Captured Accepted Binding with 'Package into Git Workspace' button");

  // 4. Click 'Package into Git Workspace' -> Runs post-Accept Workspace Compute via CONDUIT_MODEL_CMD
  await page.click("[data-plan-compute]");
  await page.waitForSelector("[data-plan-computed-workspace]", { timeout: 30000 });
  await page.waitForTimeout(1600);
  await page.screenshot({ path: `${screenshotDir}/e2e-4-workspace-packaged.png`, fullPage: false });
  const wsBadge = await page.textContent("[data-plan-computed-workspace]");
  console.log(`    [Browser] Packaged accepted plan into durable Git workspace: ${wsBadge}`);
  const { writeFileSync } = await import("node:fs");
  writeFileSync(`${process.env.RAW_VIDEO_DIR}/ws-id.txt`, wsBadge.trim().split(/\s+/)[0]);

  // 5. Transition to Workspace Inventory (s02-workspaces) to showcase the new workspace in the Console
  await page.evaluate(() => {
    if (typeof window.switchScreen === "function") {
      window.switchScreen("s02-workspaces");
    }
  });
  await page.waitForTimeout(1800);

  await context.close();
} finally {
  await browser.close();
}
EOF

RAW_WEBM="$(find "${RAW_VIDEO_DIR}" -name "*.webm" | head -n1)"
if [[ -n "${RAW_WEBM}" ]] && command -v ffmpeg >/dev/null 2>&1; then
  VIDEO_OUT="${SCREENSHOT_DIR}/conduit-excalidraw-obsidian-demo.mp4"
  echo "    Color-grading and encoding 1080p Obsidian Theme demo video to ${VIDEO_OUT}..."
  # Apply Obsidian Sapphire color grading (deep #0b1113 canvas blacks, crisp contrast, cool sapphire highlights)
  ffmpeg -y -i "${RAW_WEBM}" \
    -vf "fps=30,scale=1920:1080:flags=lanczos,eq=contrast=1.05:brightness=-0.01:saturation=1.10,colorbalance=bs=0.035:bm=0.025:bh=0.04:rs=-0.015:rm=-0.01,fade=t=in:st=0:d=0.4" \
    -c:v libx264 -preset fast -crf 18 -pix_fmt yuv420p -movflags +faststart \
    "${VIDEO_OUT}" >/dev/null 2>&1
  echo "    Saved Obsidian Theme MP4 video: ${VIDEO_OUT}"
fi

echo "==> [6/6] Verifying Hub /v1/dev-workspaces tree, file, and generated files..."
WS_LIST="$(curl --noproxy '*' -fsS -H "X-Platform-Subject: alice" "${HUB_URL}/v1/dev-workspaces")"
FRONTEND_WS_ID="$(cat "${RAW_VIDEO_DIR}/ws-id.txt")"
echo "    Frontend workspace ID: ${FRONTEND_WS_ID}"
test -n "${FRONTEND_WS_ID}"

WS_TREE="$(curl --noproxy '*' -fsS -H "X-Platform-Subject: alice" "${HUB_URL}/v1/dev-workspaces/${FRONTEND_WS_ID}/tree")"
echo "    Workspace tree entries: $(echo "${WS_TREE}" | jq -c '[.entries[].path]')"
echo "${WS_TREE}" | jq -e '.entries[] | select(.path == "Dockerfile")' >/dev/null
echo "${WS_TREE}" | jq -e '.entries[] | select(.path == "zarf.yaml")' >/dev/null
echo "${WS_TREE}" | jq -e '.entries[] | select(.path == "uds-package.yaml")' >/dev/null

UDS_FILE="$(curl --noproxy '*' -fsS -H "X-Platform-Subject: alice" "${HUB_URL}/v1/dev-workspaces/${FRONTEND_WS_ID}/file?path=uds-package.yaml")"
echo "${UDS_FILE}" | jq -e '.content | contains("uds.dev/v1alpha1")' >/dev/null
echo "    uds-package.yaml verified in durable workspace ${FRONTEND_WS_ID}"

echo "==> End-to-End CLI + Frontend Excalidraw AI Packaging Demo PASSED!"
