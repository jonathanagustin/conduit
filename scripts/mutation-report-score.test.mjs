import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { equivalentReview, quality, scoreReport, sha256 } from "./mutation-report-score.mjs";
const root = mkdtempSync(join(tmpdir(), "conduit-mutation-review-"));
const name = "internal/reporting/domain";
try {
  mkdirSync(join(root, name), { recursive: true });
  mkdirSync(join(root, "docs/operations"), { recursive: true });
  const source = "package domain\n// fixture for source identity\n";
  writeFileSync(join(root, name, "fleet.go"), source);
  const mutant = { file: "fleet.go", type: "CONDITIONALS_BOUNDARY", line: 2, column: 1, reason: "Fixture review argument: this named mutation preserves the observed fixture value." };
  const entry = { sources: { "fleet.go": sha256(source) }, mutants: [mutant] };
  const save = (value = entry) => writeFileSync(join(root, "docs/operations/mutation-equivalents.json"), JSON.stringify({ schemaVersion: 1, packages: { [name]: value } }));
  save();
  const report = { mutants_killed: 1, mutants_lived: 1, mutants_total: 2, test_efficacy: 50, mutations_coverage: 100, files: [{ file_name: "fleet.go", mutations: [{ ...mutant, status: "LIVED" }] }] };
  const score = scoreReport(root, name, report);
  assert.equal(score.killed, 1);
  assert.equal(score.lived, 1);
  assert.equal(score.efficacy, 50);
  assert.equal(score.equivalent, 1);
  assert.equal(score.nonEquivalentEfficacy, 100);
  const unknown = structuredClone(report);
  unknown.files[0].mutations.push({ type: "INCREMENT_DECREMENT", status: "LIVED", line: 3, column: 1 });
  Object.assign(unknown, { mutants_lived: 2, mutants_total: 3, test_efficacy: 100 / 3 });
  assert.equal(scoreReport(root, name, unknown).nonEquivalentEfficacy, 50, "unreviewed survivors must remain in the denominator");
  const killed = structuredClone(report); killed.files[0].mutations[0].status = "KILLED";
  assert.throws(() => scoreReport(root, name, killed), /no longer LIVED/);
  const missing = structuredClone(report); missing.files = [];
  assert.throws(() => scoreReport(root, name, missing), /missing/);
  const duplicate = structuredClone(report); duplicate.files[0].mutations.push(duplicate.files[0].mutations[0]);
  assert.throws(() => scoreReport(root, name, duplicate), /duplicate engine/);
  writeFileSync(join(root, name, "fleet.go"), source + "// source changed\n");
  assert.throws(() => scoreReport(root, name, report), /stale equivalent source/);
  writeFileSync(join(root, name, "fleet.go"), source);
  save({ ...entry, mutants: [mutant, mutant] });
  assert.throws(() => equivalentReview(root, name), /duplicate equivalent/);
  save();
  const review = equivalentReview(root, name);
  assert.throws(() => quality({ killed: 1, lived: 1 }, review), /omitted/);
  const timed = structuredClone(report); timed.files[0].mutations.push({type:"ARITHMETIC_BASE", status:"TIMED OUT", line:4, column:1});
  assert.throws(() => scoreReport(root, name, timed), /timed-out mutants/);
  assert.throws(() => quality({ ...score, equivalent: 2 }, review), /invalid equivalent count/);
  assert.throws(() => quality({ ...score, nonEquivalentEfficacy: 99 }, review), /does not follow/);
  assert.throws(() => quality({ ...score, equivalentManifestSha256: "wrong" }, review), /does not match/);
  assert.throws(() => scoreReport(root, name, { ...report, test_efficacy: 100 }), /inconsistent engine/);
  assert.equal(quality({ killed: 1, lived: 1 }), 50, "legacy raw measurements get no exemption");
  console.log("PASS mutation scoring: raw counts preserved; only source-bound, individually reviewed survivors are classified");
} finally { rmSync(root, { recursive: true, force: true }); }
