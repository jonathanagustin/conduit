import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { attributionFooter, attributionIdentity, commitDefects, conventionalSubject, proposalDefects } from "./verify-commit-metadata.mjs";

const sha = "a".repeat(40);
const author = { name: "Alice Example", email: "alice@example.invalid" };
const commit = (message = "feat(spaces): persist grouping", extra = {}) => ({ sha, commit: { message, author, committer: author, ...extra } });
assert.deepEqual(commitDefects(commit()), []);
for (const subject of ["fix!: preserve scope", "chore(deps): update a dependency", "security(policy): tighten admission"]) assert.equal(conventionalSubject(subject), true);
for (const subject of ["Add a feature", "Merge pull request #123", "fix:no space", "feat: ", "fix: first\nsecond"]) assert.equal(conventionalSubject(subject), false);
assert.equal(attributionIdentity({ name: "Claude Dubois", email: "claude.dubois@example.invalid" }), false);
assert.equal(attributionIdentity({ name: "Human Engineer", email: "human@openai.com" }), false);
assert.deepEqual(commitDefects(commit("fix: keep a human coauthor\n\nCo-authored-by: Bob Example <bob@example.invalid>")), []);
for (const identity of [{ name: "Claude Opus 4.8", email: "noreply@anthropic.com" }, { name: "Cursor Agent", email: "cursoragent@cursor.com" }, { name: "github-copilot[bot]", email: "175728472+github-copilot[bot]@users.noreply.github.com" }]) {
  assert.ok(commitDefects(commit(undefined, { author: identity })).some((value) => value.includes("author metadata")));
  assert.ok(commitDefects(commit(undefined, { committer: identity })).some((value) => value.includes("committer metadata")));
}
for (const footer of ["Co-authored-by: Cursor Agent <cursoragent@cursor.com>", "co-authored-by: Claude Opus 4.8 <noreply@anthropic.com>", "Claude-Session: https://claude.ai/code/session_example", "🤖 Generated with [Claude Code](https://claude.ai/code)", "_Generated by [Codex](https://example.invalid)_"]) assert.equal(attributionFooter(`fix: a change\n\n${footer}`), true);
assert.equal(attributionFooter("feat: add Codex runtime controls\n\nImplement Claude-compatible model selection."), false);
assert.equal(attributionFooter("test: reject bad metadata\n\n```text\nCo-authored-by: Cursor Agent <cursoragent@cursor.com>\n```"), false);
assert.equal(attributionFooter("> Generated by Claude Code\n\nDescribe a historical example."), false);
const sessionFooters = [
  "<!-- CURSOR_AGENT_PR_BODY_BEGIN -->",
  "<!-- CURSOR_AGENT_PR_BODY_END -->",
  '<div><a href="https://cursor.com/agents/example">Open in Web</a></div>',
  '<a href="https://cursor.com/background-agent?bcId=example&cursor_ref=pr_footer">Open in editor</a>',
  "[Session](https://cursor.com/agents/example)",
];
for (const footer of sessionFooters) {
  assert.equal(attributionFooter(`Describe the change.\n\n${footer}`), true);
  assert.equal(attributionFooter(`Document an example:\n\n\u0060\u0060\u0060html\n${footer}\n\u0060\u0060\u0060`), false);
  assert.equal(attributionFooter(`> ${footer}\n\nDescribe a historical example.`), false);
}
assert.equal(attributionFooter("Update tooling documentation: https://cursor.com/docs and https://cursor.com/agents"), false);
assert.equal(attributionFooter("[Screenshot](https://cursor.com/agents/example/artifacts?path=screenshot.png)"), false);
assert.ok(commitDefects({ sha, message: "fix: incomplete identity" }).includes("missing author metadata"));
const proposal = { title: "feat: support grouping", body: "Describe native behavior.", head: { sha }, commits: 1 };
assert.deepEqual(proposalDefects(proposal, [commit()], sha), []);
assert.ok(proposalDefects({ ...proposal, title: "Add grouping" }, [commit()], sha).some((value) => value.includes("pull request title")));
assert.ok(proposalDefects({ ...proposal, body: "Generated by Claude Code" }, [commit()], sha).some((value) => value.includes("pull request attribution")));
for (const body of sessionFooters) assert.ok(proposalDefects({ ...proposal, body }, [commit()], sha).some((value) => value.includes("pull request attribution")));
assert.ok(proposalDefects(proposal, [], sha).some((value) => value.includes("incomplete")));
assert.ok(proposalDefects({ ...proposal, commits: 2 }, [commit()], sha).some((value) => value.includes("incomplete")));
assert.ok(proposalDefects({ ...proposal, commits: 2 }, [commit(), commit()], sha).some((value) => value.includes("incomplete")));

assert.ok(proposalDefects(proposal, [commit()], "b".repeat(40)).some((value) => value.includes("moved")));

const directory = mkdtempSync(join(tmpdir(), "conduit-commit-metadata-"));
try {
  const script = resolve("scripts/verify-commit-metadata.mjs");
  const git = (...args) => execFileSync("git", args, { cwd: directory, stdio: "pipe", env: { ...process.env, GIT_CONFIG_GLOBAL: "/dev/null", GIT_CONFIG_SYSTEM: "/dev/null" } });
  git("init", "--quiet"); git("config", "user.name", author.name); git("config", "user.email", author.email);
  git("commit", "--quiet", "--allow-empty", "-m", "chore: initialize fixture"); git("update-ref", "refs/remotes/origin/main", "HEAD");
  git("commit", "--quiet", "--allow-empty", "-m", "fix: preserve data");
  const local = () => spawnSync(process.execPath, [script], { cwd: directory, encoding: "utf8" });
  assert.equal(local().status, 0);
  git("commit", "--quiet", "--allow-empty", "-m", "Add an unreviewed subject");
  const rejected = local(); assert.equal(rejected.status, 1); assert.match(rejected.stderr, /Conventional Commit subject/);
  const bin = join(directory, "bin"); mkdirSync(bin);
  writeFileSync(join(bin, "gh"), `#!/usr/bin/env node
const fs = require("node:fs"), root = process.env.META_FIXTURE_DIRECTORY;
if (process.argv[3].endsWith("/commits")) {
 const contents = fs.readFileSync(root + "/commits.json", "utf8");
 try { for (const page of JSON.parse(contents)) console.log(JSON.stringify(page)); }
 catch { console.log(contents); }
} else {
 const moved = process.env.META_CHANGE_AFTER_READ === "1" && fs.existsSync(root + "/read-marker");
 fs.writeFileSync(root + "/read-marker", "1");
 process.stdout.write(fs.readFileSync(root + (moved ? "/moved.json" : "/pr.json")));
}
`, { mode: 0o755 });
  writeFileSync(join(directory, "pr.json"), JSON.stringify(proposal));
  writeFileSync(join(directory, "commits.json"), JSON.stringify([[commit()]]));
  const remote = (extra = {}) => spawnSync(process.execPath, [script, "--github"], { encoding: "utf8", env: { ...process.env, PATH: `${bin}:${process.env.PATH}`, META_FIXTURE_DIRECTORY: directory, GITHUB_REPOSITORY: "example/project", PULL_REQUEST_NUMBER: "17", GATE_SHA: sha, ...extra } });
  assert.equal(remote().status, 0);
  writeFileSync(join(directory, "pr.json"), JSON.stringify({ ...proposal, body: sessionFooters[2] }));
  const sessionBadge = remote(); assert.equal(sessionBadge.status, 1); assert.match(sessionBadge.stderr, /pull request attribution/); assert.doesNotMatch(sessionBadge.stderr, /cursor\.com/);
  writeFileSync(join(directory, "pr.json"), JSON.stringify(proposal));
  writeFileSync(join(directory, "commits.json"), JSON.stringify([[commit("fix: clean")], [{ ...commit(), sha: "b".repeat(40) }]]));
  const moved = remote(); assert.equal(moved.status, 1); assert.match(moved.stderr, /head moved/);
  writeFileSync(join(directory, "commits.json"), JSON.stringify([[commit("fix: change\n\nCo-authored-by: Cursor Agent <cursoragent@cursor.com>")]]));
  const attributed = remote(); assert.equal(attributed.status, 1); assert.match(attributed.stderr, /attribution/); assert.doesNotMatch(attributed.stderr, /cursoragent@/);
  writeFileSync(join(directory, "commits.json"), JSON.stringify([[{ ...commit("fix: change\n\nCo-authored-by: Cursor Agent <cursoragent@cursor.com>"), sha: "b".repeat(40) }], [commit()]]));
  writeFileSync(join(directory, "pr.json"), JSON.stringify({ ...proposal, commits: 2 }));
  const earlierPage = remote(); assert.equal(earlierPage.status, 1); assert.match(earlierPage.stderr, /attribution/); assert.doesNotMatch(earlierPage.stderr, /head moved/);
  writeFileSync(join(directory, "commits.json"), JSON.stringify([[commit()]]));
  writeFileSync(join(directory, "pr.json"), JSON.stringify(proposal));
  writeFileSync(join(directory, "moved.json"), JSON.stringify({ ...proposal, head: { sha: "b".repeat(40) } }));
  rmSync(join(directory, "read-marker"), { force: true });
  const duringRead = remote({ META_CHANGE_AFTER_READ: "1" }); assert.equal(duringRead.status, 1); assert.match(duringRead.stderr, /head moved while metadata was read/);
  writeFileSync(join(directory, "commits.json"), "ultra-sensitive-malformed-response");
  const malformed = remote(); assert.equal(malformed.status, 1); assert.match(malformed.stderr, /unable to read/); assert.doesNotMatch(malformed.stderr, /ultra-sensitive/);

} finally { rmSync(directory, { recursive: true, force: true }); }
console.log("PASS commit metadata policy: subjects, identities, trailers, pagination, and authenticated head");
