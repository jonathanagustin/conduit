#!/usr/bin/env node
// Reports how far the bounded-context migration has actually got.
//
// The register says H83 is OPEN and the boundaries document lists eight
// contexts to extract, but neither says how much has moved, so the honest
// answer has been "someone would have to go and count". The first count found
// the monolith 2,073 lines *larger* than when the migration began, which is the
// kind of thing a migration should not be able to hide.
//
// Everything here is measured from the tree rather than declared. There is no
// checked-in number to update and therefore none to forget.
//
// Run: node scripts/report-migration-progress.mjs [--json]
import { readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const internal = join(root, "internal");

// The contexts bounded-contexts.md names, in the order it sequences them.
const CONTEXTS = [
  "reporting", "identity", "artifacts", "catalog",
  "environments", "governance", "delivery", "execution",
];

// Two kinds of .go file sit inside the monolith without being the monolith,
// and counting them measures the wrong thing:
//
//   - `//go:build ignore` command files. They are build-time tools that no
//     build ever compiles into the package; the generator for the PostgreSQL
//     adapter is one.
//   - `Code generated by ... DO NOT EDIT.` output. Its size is a property of
//     the generator's input, not of how much behaviour lives here, and nobody
//     can decompose it by hand.
//
// Both are still reported, separately, so this cannot become a hiding place:
// a generator that emits an ever-larger adapter stays visible, it just does
// not consume the ratchet that exists to force hand-written decisions out.
const classify = (path) => {
  const head = readFileSync(path, "utf8").split("\n", 15).join("\n");
  if (/^\/\/go:build ignore\b/m.test(head)) return "tool";
  if (/Code generated by .*DO NOT EDIT\./.test(head)) return "generated";
  return "source";
};

const allGoFiles = (directory) => {
  const out = [];
  const walk = (dir) => {
    let entries;
    try { entries = readdirSync(dir); } catch { return; }
    for (const entry of entries) {
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) walk(path);
      else if (entry.endsWith(".go") && !entry.endsWith("_test.go")) out.push(path);
    }
  };
  walk(directory);
  return out;
};

const goFiles = (directory) =>
  allGoFiles(directory).filter((path) => classify(path) === "source");

const excludedFiles = (directory) =>
  allGoFiles(directory).filter((path) => classify(path) !== "source");

const lines = (paths) =>
  paths.reduce((total, path) => total + readFileSync(path, "utf8").split("\n").length, 0);

const monolith = goFiles(join(internal, "controlplane"));
const monolithExcluded = excludedFiles(join(internal, "controlplane")).map((path) => ({
  file: path.slice(join(internal, "controlplane").length + 1),
  kind: classify(path),
  lines: lines([path]),
}));

const extracted = CONTEXTS.map((name) => {
  const paths = goFiles(join(internal, name));
  return { context: name, present: paths.length > 0, files: paths.length, lines: lines(paths) };
});

// A context that only holds adapters has not taken ownership of anything; one
// with a domain has. The distinction matters because adapters can be written
// without moving a single decision out of the monolith.
const withDomain = extracted.filter((c) =>
  goFiles(join(internal, c.context)).some((p) => p.includes("/domain/"))
);

const report = {
  monolith: { files: monolith.length, lines: lines(monolith) },
  monolithExcluded,
  contextsNamed: CONTEXTS.length,
  contextsPresent: extracted.filter((c) => c.present).length,
  contextsWithDomain: withDomain.length,
  contexts: extracted,
  compositionRootPresent: goFiles(join(internal, "hub", "composition")).length > 0,
};

// The line ceiling that used to live here is gone, deliberately.
//
// It was a ratchet: a checked-in maximum for internal/controlplane that the
// bounded-context migration could only move down, enforced as a gate. It did
// work -- it is what forced the Apollo substitution language out into
// internal/apollo/substitution rather than letting the monolith keep it.
//
// It was removed because the cost landed on the wrong work. At zero headroom it
// blocked changes that had nothing to do with the monolith's size: a two-line
// fix preserving a rejected change request's rationale, a one-line fix to an
// export-pipeline identifier. Coupling every small fix to "first go extract a
// package" is a tax on unrelated correctness work, and correctness work is the
// thing this repository least wants to discourage.
//
// What remains is this report, which is the part that was always useful: what
// the monolith weighs, which contexts exist, and whether the composition root is
// present. Read it to see where the migration stands. Nothing fails a build on
// it, and `--gate` is accepted and does nothing so old invocations do not break.
if (process.argv.includes("--gate")) {
  console.log(
    `internal/controlplane is ${report.monolith.lines} lines across ${report.monolith.files} files. ` +
    "The ceiling gate was removed; this is a report, not a verdict."
  );
  process.exit(0);
}

if (process.argv.includes("--json")) {
  console.log(JSON.stringify(report, null, 2));
} else {
  console.log(`internal/controlplane   ${report.monolith.files} files, ${report.monolith.lines} lines`);
  for (const excluded of report.monolithExcluded) {
    console.log(`  not counted           ${excluded.file} (${excluded.kind}, ${excluded.lines} lines)`);
  }
  console.log(`contexts extracted      ${report.contextsPresent}/${report.contextsNamed} present, ${report.contextsWithDomain} owning a domain`);
  console.log(`hub composition root    ${report.compositionRootPresent ? "present" : "MISSING"}`);
  console.log("");
  for (const context of report.contexts) {
    const state = context.present
      ? `${String(context.files).padStart(3)} files, ${String(context.lines).padStart(5)} lines`
      : "  not started";
    console.log(`  ${context.context.padEnd(14)} ${state}`);
  }
  console.log("");
  console.log("The monolith line count is the number that matters: a migration that");
  console.log("adds contexts while controlplane keeps growing has not moved anything.");
}
