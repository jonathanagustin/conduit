// Package domain owns what Conduit can honestly say about the Apollo-shaped
// GraphQL interface it serves.
//
// Two different questions get confused whenever an interface is part recovered
// and part invented, and this package keeps them apart:
//
//   - Who established this coordinate? An authorized Apollo Hub answered for it
//     (OBSERVED), or Apollo publishes the name or documents the concept while no
//     Hub established it in GraphQL (DOCUMENTED), or Conduit thought of it and
//     Apollo makes no claim of any kind (CONDUIT_NATIVE). The served SDL states
//     this per field.
//   - Can Conduit answer it? Declaring a coordinate the Hub answers for is not
//     the same as holding the data behind it. Conduit has no bundles and no
//     space identifiers, so several OBSERVED coordinates are declared and
//     unanswerable here.
//
// The second question is why this package refuses rather than returns null. A
// null reads as "there is no value"; an unserved coordinate means "Conduit
// never had one". Reporting them the same way would let a client record an
// absence Conduit never observed, which is the failure this whole interface was
// built to avoid.
//
// Nothing here reads a store, a clock or a request, and nothing here parses
// GraphQL. It is given the SDL text and returns findings.
package domain

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

// Tier is the SDL's own answer to who established a coordinate.
type Tier string

const (
	// Observed was recovered from an authorized Apollo Hub and reproduced from
	// the recovery record.
	Observed Tier = "OBSERVED"
	// Documented carries an Apollo name or an Apollo concept taken from published
	// documentation, verified against the pinned OpenAPI snapshot and the
	// committed documentation manifest. No Hub established it in GraphQL, so it
	// is not an Apollo compatibility claim -- but Conduit did not name it.
	Documented Tier = "DOCUMENTED"
	// ConduitNative was invented here. It is not an Apollo compatibility claim
	// and it is displaced the moment a capture recovers the same coordinate.
	ConduitNative Tier = "CONDUIT_NATIVE"
)

// Established answers whether an Apollo Hub is behind a coordinate. It is the
// distinction that matters for a compatibility claim: DOCUMENTED and
// CONDUIT_NATIVE differ in how much evidence Conduit has, but neither is a Hub
// saying so, and both were added to the interface by Conduit.
func (tier Tier) Established() bool { return tier == Observed }

// Coordinate is one field of one type: the unit everything here is stated in,
// because "the interface" is too coarse to be audited and a type is too coarse
// to be displaced.
type Coordinate struct {
	Type  string
	Field string
}

func (coordinate Coordinate) String() string {
	return coordinate.Type + "." + coordinate.Field
}

// Interface is the provenance the served SDL declares, read out of the SDL
// itself rather than restated. A second list would be a second thing to drift.
type Interface struct {
	tiers map[Coordinate]Tier
	// cardinality is recorded only where the SDL states it, which is only where
	// a source OTHER than the one that established the field established that it
	// is a list. Absent means the field's own tier covers it.
	cardinality map[Coordinate]Tier
	// valueTier separates the provenance of a field's DECLARATION from the
	// provenance of the VALUE served behind it.
	//
	// tier answers "why does this field exist in Conduit's schema" -- almost
	// always because a capture recovered it from an Apollo Hub. It has never
	// answered "where did this particular string come from", and while the two
	// were always the same nobody needed it to. ADR 0007 makes them differ: a
	// coordinate Apollo declares can now be served from a value Conduit invented,
	// which is legal precisely because valueTier says so on the wire.
	//
	// Absent means it equals the field's tier, so every coordinate served before
	// ADR 0007 keeps its meaning without being touched.
	valueTier map[Coordinate]Tier
}

var (
	typeHeader   = regexp.MustCompile(`^type ([A-Za-z_][A-Za-z0-9_]*) \{$`)
	fieldWithARR = regexp.MustCompile(
		`^ {2}([a-zA-Z_][a-zA-Z0-9_]*)[^@]*@provenance\(tier: ([A-Z_]+)` +
			`(?:, valueTier: ([A-Z_]+))?(?:, cardinality: ([A-Z_]+))?\)$`,
	)
)

// ReadProvenance reads every field's tier out of the served SDL.
//
// It is a line reader rather than a GraphQL parse because the SDL it reads is
// generated by build-interface-schema.mjs in exactly this shape, and because a
// field that carries no annotation must be an error rather than a default. A
// tolerant parser would silently accept an unannotated field, and an
// unannotated field is precisely the one whose provenance nobody can state.
func ReadProvenance(sdl string) (Interface, error) {
	tiers := make(map[Coordinate]Tier)
	cardinality := make(map[Coordinate]Tier)
	valueTier := make(map[Coordinate]Tier)
	currentType := ""
	for number, line := range strings.Split(sdl, "\n") {
		switch {
		case typeHeader.MatchString(line):
			currentType = typeHeader.FindStringSubmatch(line)[1]
		case line == "}":
			currentType = ""
		case currentType != "" && strings.HasPrefix(line, "  "):
			match := fieldWithARR.FindStringSubmatch(line)
			if match == nil {
				return Interface{}, fmt.Errorf(
					"%s:%d declares a field with no provenance: %q. Every served field must say who "+
						"established it, so an invented one cannot pass as recovered",
					currentType, number+1, strings.TrimSpace(line),
				)
			}
			tier := Tier(match[2])
			if tier != Observed && tier != Documented && tier != ConduitNative {
				return Interface{}, fmt.Errorf("%s.%s declares unknown provenance tier %q", currentType, match[1], tier)
			}
			coordinate := Coordinate{Type: currentType, Field: match[1]}
			tiers[coordinate] = tier
			// A cardinality that is present is checked the same way the tier is.
			// It is a provenance claim, and an unreadable one must not pass as an
			// absent one -- absent means "the field's tier covers it", which is a
			// different and stronger statement.
			if match[3] != "" {
				stated := Tier(match[3])
				if stated != Observed && stated != Documented && stated != ConduitNative {
					return Interface{}, fmt.Errorf(
						"%s.%s declares unknown value provenance %q", currentType, match[1], stated,
					)
				}
				valueTier[coordinate] = stated
			}
			// Checked the same way, for the same reason: an unreadable value tier
			// must not pass as an absent one. Absent means "the value came from
			// wherever the declaration did", which is the stronger claim.
			if match[4] != "" {
				stated := Tier(match[4])
				if stated != Observed && stated != Documented && stated != ConduitNative {
					return Interface{}, fmt.Errorf(
						"%s.%s declares unknown cardinality provenance %q", currentType, match[1], stated,
					)
				}
				cardinality[coordinate] = stated
			}
		}
	}
	if len(tiers) == 0 {
		return Interface{}, fmt.Errorf("no annotated field found; this is not the served interface")
	}
	return Interface{tiers: tiers, cardinality: cardinality, valueTier: valueTier}, nil
}

// CardinalityOf answers who established that a coordinate is a list, when that
// is someone other than whoever established the field. The second result is
// false when the SDL states nothing, which means the field's own tier covers it
// -- a scalar, or a list the same source carried.
func (declared Interface) CardinalityOf(coordinate Coordinate) (Tier, bool) {
	tier, found := declared.cardinality[coordinate]
	return tier, found
}

// ValueTierOf answers where the VALUE behind a coordinate came from, when that
// differs from where the declaration came from. The second result is false when
// the SDL states nothing, which means the two are the same.
//
// A caller deciding whether a served value is Conduit's own must use this rather
// than TierOf. TierOf will say OBSERVED for an invented value and be correct --
// Apollo really did declare the field -- which is exactly the conflation ADR 0005
// warned about and ADR 0007 resolves by separating the two questions.
func (declared Interface) ValueTierOf(coordinate Coordinate) (Tier, bool) {
	tier, found := declared.valueTier[coordinate]
	return tier, found
}

// InventedValues is every coordinate serving a value Conduit constructed.
//
// Exposed so a gate can ask the interface directly rather than re-reading the
// SDL with a second regex that could disagree with this one.
func (declared Interface) InventedValues() []Coordinate {
	invented := []Coordinate{}
	for coordinate, tier := range declared.valueTier {
		if tier == ConduitNative {
			invented = append(invented, coordinate)
		}
	}
	sort.Slice(invented, func(i, j int) bool { return invented[i].String() < invented[j].String() })
	return invented
}

// TierOf answers who established a coordinate. The second result is false for a
// coordinate the served interface does not declare at all, which is a different
// fact from an untiered one and never occurs in a validated query.
func (declared Interface) TierOf(coordinate Coordinate) (Tier, bool) {
	tier, found := declared.tiers[coordinate]
	return tier, found
}

// Coordinates lists every declared coordinate in a stable order, so a caller
// can compare the interface against something else and report the difference
// the same way twice.
func (declared Interface) Coordinates() []Coordinate {
	coordinates := make([]Coordinate, 0, len(declared.tiers))
	for coordinate := range declared.tiers {
		coordinates = append(coordinates, coordinate)
	}
	sort.Slice(coordinates, func(left, right int) bool {
		return coordinates[left].String() < coordinates[right].String()
	})
	return coordinates
}

// Count returns how many coordinates carry each tier. These are the numbers the
// provenance report states, recomputed from the SDL the server actually serves
// rather than trusted from the report.
func (declared Interface) Count() (observed, documented, native int) {
	for _, tier := range declared.tiers {
		switch tier {
		case Observed:
			observed++
		case Documented:
			documented++
		default:
			native++
		}
	}
	return observed, documented, native
}
