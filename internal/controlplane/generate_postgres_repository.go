//go:build ignore

// Command generate_postgres_repository emits the mechanical PostgreSQL
// adapters for every MemoryRepository method. The in-memory implementation is
// the executable domain contract; the generated adapter changes only the
// transaction and durability boundary.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	fset := token.NewFileSet()
	packages, err := parser.ParseDir(fset, ".", func(info os.FileInfo) bool {
		return !strings.HasSuffix(info.Name(), "_test.go") && info.Name() != "postgres_repository_gen.go"
	}, 0)
	if err != nil {
		panic(err)
	}
	pkg := packages["controlplane"]
	if pkg == nil {
		panic("controlplane package not found; run from internal/controlplane")
	}
	methods := make([]*ast.FuncDecl, 0)
	for _, file := range pkg.Files {
		for _, declaration := range file.Decls {
			function, ok := declaration.(*ast.FuncDecl)
			if !ok || function.Recv == nil || len(function.Recv.List) != 1 {
				continue
			}
			pointer, ok := function.Recv.List[0].Type.(*ast.StarExpr)
			if !ok {
				continue
			}
			identifier, receiverIsIdentifier := pointer.X.(*ast.Ident)
			if !receiverIsIdentifier || identifier.Name != "MemoryRepository" {
				continue
			}
			if !methodExported(function.Name.Name) {
				continue
			}
			if function.Name.Name == "PutBlob" || function.Name.Name == "OpenBlob" || function.Name.Name == "Transaction" || function.Name.Name == "AppendAuthorizationAudit" || function.Name.Name == "ListAuthorizationAudit" || function.Name.Name == "ReadCommittedEvents" {
				continue
			}
			methods = append(methods, function)
		}
	}
	sort.Slice(methods, func(i, j int) bool { return methods[i].Name.Name < methods[j].Name.Name })

	var output bytes.Buffer
	output.WriteString("// Code generated by go run generate_postgres_repository.go; DO NOT EDIT.\n\n")
	output.WriteString("package controlplane\n\n")
	output.WriteString("import (\n\t\"context\"\n\t\"io\"\n\t\"time\"\n)\n\n")
	output.WriteString("var (\n\t_ Repository = (*PostgresRepository)(nil)\n\t_ io.Reader\n\t_ time.Time\n)\n\n")

	for _, method := range methods {
		emitMethod(&output, fset, method)
	}
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		panic(fmt.Errorf("format generated adapter: %w\n%s", err, output.String()))
	}
	target := filepath.Join("postgres_repository_gen.go")
	if err := os.WriteFile(target, formatted, 0o644); err != nil {
		panic(err)
	}
}

func methodExported(name string) bool {
	return name != "" && name[0] >= 'A' && name[0] <= 'Z'
}

func emitMethod(output *bytes.Buffer, fset *token.FileSet, method *ast.FuncDecl) {
	parameterNames := make([]string, 0)
	parameterText := fieldListText(fset, method.Type.Params, true, &parameterNames)
	resultNames := make([]string, 0)
	resultTypes := make([]string, 0)
	for _, field := range method.Type.Results.List {
		typeText := nodeText(fset, field.Type)
		count := len(field.Names)
		if count == 0 {
			count = 1
		}
		for range count {
			resultTypes = append(resultTypes, typeText)
		}
	}
	if len(resultTypes) == 0 || resultTypes[len(resultTypes)-1] != "error" {
		panic("repository method must return error last: " + method.Name.Name)
	}
	valueTypes := resultTypes[:len(resultTypes)-1]
	for index := range valueTypes {
		resultNames = append(resultNames, fmt.Sprintf("result%d", index))
	}
	write := !strings.HasPrefix(method.Name.Name, "Get") &&
		!strings.HasPrefix(method.Name.Name, "List")

	fmt.Fprintf(output, "func (repository *PostgresRepository) %s(%s) (%s) {\n",
		method.Name.Name, parameterText, strings.Join(resultTypes, ", "))
	for index, resultType := range valueTypes {
		fmt.Fprintf(output, "\tvar result%d %s\n", index, resultType)
	}
	fmt.Fprintf(output, "\terr := repository.withState(ctx, %t, func(memory *MemoryRepository) error {\n", write)
	assignment := append(append([]string(nil), resultNames...), "innerErr")
	output.WriteString("\t\tvar innerErr error\n")
	fmt.Fprintf(output, "\t\t%s = memory.%s(%s)\n", strings.Join(assignment, ", "), method.Name.Name, strings.Join(parameterNames, ", "))
	output.WriteString("\t\treturn innerErr\n\t})\n")
	returns := append(append([]string(nil), resultNames...), "err")
	fmt.Fprintf(output, "\treturn %s\n}\n\n", strings.Join(returns, ", "))
}

func fieldListText(fset *token.FileSet, fields *ast.FieldList, renameContext bool, names *[]string) string {
	parts := make([]string, 0)
	for _, field := range fields.List {
		fieldNames := field.Names
		if len(fieldNames) == 0 {
			panic("unnamed repository parameter")
		}
		for _, fieldName := range fieldNames {
			name := fieldName.Name
			if renameContext && name == "_" && nodeText(fset, field.Type) == "context.Context" {
				name = "ctx"
			}
			*names = append(*names, name)
			parts = append(parts, name+" "+nodeText(fset, field.Type))
		}
	}
	return strings.Join(parts, ", ")
}

func nodeText(fset *token.FileSet, node ast.Node) string {
	var output bytes.Buffer
	if err := printer.Fprint(&output, fset, node); err != nil {
		panic(err)
	}
	return output.String()
}
