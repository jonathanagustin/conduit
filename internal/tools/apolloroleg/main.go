// Command apolloroleg emits the Apollo authorization role table from the
// captured tenant authorization graph.
//
// The role, operation, workflow, and category identifiers, and every edge
// between them, are tenant-observed configuration. Hand-transcribing them would
// reproduce the failure AGENTS.md 0a describes: a hand-written table about
// someone else's system fails silently and confidently. The capture is
// therefore the single source, and a role that the tenant does not serve cannot
// be declared here.
//
// It generates the vocabulary and its edges, and nothing else. How a Platform
// grant expands into Platform operations stays hand-written in governance.go,
// because that is Platform's own authority algebra rather than a recovered
// fact. Apollo composes roles out of other roles; Platform expands roles into
// abstract operations. Those are different algebras and the generated table
// deliberately does not pretend otherwise.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

type graphEntry struct {
	ID               string   `json:"id"`
	DisplayName      string   `json:"displayName"`
	Name             string   `json:"name"`
	Description      string   `json:"description"`
	Operations       []string `json:"operations"`
	CanAssigns       []string `json:"canAssigns"`
	TrackedWorkflows []string `json:"trackedWorkflows"`
	Workflows        []string `json:"workflows"`
	IsDeleted        bool     `json:"isDeleted"`
}

type capture struct {
	Source struct {
		Endpoint       string `json:"endpoint"`
		ResponseSha256 string `json:"responseSha256"`
	} `json:"source"`
	GraphCloses bool `json:"graphCloses"`
	Graph       struct {
		Roles      map[string]graphEntry `json:"roles"`
		Operations map[string]graphEntry `json:"operations"`
		Workflows  map[string]graphEntry `json:"workflows"`
		Categories map[string]graphEntry `json:"categories"`
	} `json:"graph"`
}

func main() {
	in := flag.String("in", "docs/evidence/apollo-authorization-graph.json", "captured authorization graph")
	out := flag.String("out", "internal/apollo/roles.gen.go", "generated file")
	flag.Parse()

	raw, err := os.ReadFile(*in)
	if err != nil {
		fail(err)
	}
	var doc capture
	if err := json.Unmarshal(raw, &doc); err != nil {
		fail(err)
	}
	if len(doc.Graph.Roles) == 0 {
		fail(fmt.Errorf("capture declares no roles"))
	}
	// A graph that does not close has edges pointing at definitions it does not
	// carry. Generating from it would emit a role whose grants cannot be
	// resolved, so refuse rather than emit a table with dangling references.
	if !doc.GraphCloses {
		fail(fmt.Errorf("capture does not close: refusing to generate a table with unresolved edges"))
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by apolloroleg from %s (%s). DO NOT EDIT.\n\n",
		doc.Source.Endpoint, doc.Source.ResponseSha256)
	buf.WriteString("package apollo\n\n")

	buf.WriteString(`// Role is one role the Apollo authorization model declares. Operations
// and CanAssigns are Apollo's own composition: a role grants other roles, and
// may grant operations owned by other products. Nothing here says what
// authority Platform attaches to the role.
type Role struct {
	ID          string
	DisplayName string
	Description string
	Operations  []string
	CanAssigns  []string
	Deleted     bool
}

`)

	fmt.Fprintf(&buf, "// AuthorizationGraphDigest pins the exact response the table came from.\n")
	fmt.Fprintf(&buf, "const AuthorizationGraphDigest = %q\n\n", doc.Source.ResponseSha256)

	fmt.Fprintf(&buf, "// Roles is every role the captured tenant serves, keyed by identifier.\n")
	buf.WriteString("var Roles = map[string]Role{\n")
	for _, id := range sortedKeys(doc.Graph.Roles) {
		entry := doc.Graph.Roles[id]
		fmt.Fprintf(&buf, "\t%q: {\n\t\tID: %q,\n", id, id)
		if entry.DisplayName != "" {
			fmt.Fprintf(&buf, "\t\tDisplayName: %q,\n", entry.DisplayName)
		}
		if entry.Description != "" {
			fmt.Fprintf(&buf, "\t\tDescription: %q,\n", entry.Description)
		}
		writeStrings(&buf, "Operations", entry.Operations)
		writeStrings(&buf, "CanAssigns", entry.CanAssigns)
		if entry.IsDeleted {
			buf.WriteString("\t\tDeleted: true,\n")
		}
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n\n")

	writeIdentifierSet(&buf, "Operations",
		"Operations is every operation reachable from an Apollo role, including\n// operations owned by other products.",
		doc.Graph.Operations)
	writeIdentifierSet(&buf, "Workflows",
		"Workflows is every workflow reachable from an Apollo role or category.",
		doc.Graph.Workflows)
	writeIdentifierSet(&buf, "Categories",
		"Categories is every Apollo permission category.",
		doc.Graph.Categories)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fail(err)
	}
	fmt.Fprintf(os.Stderr, "wrote %s: roles=%d operations=%d workflows=%d categories=%d\n",
		*out, len(doc.Graph.Roles), len(doc.Graph.Operations),
		len(doc.Graph.Workflows), len(doc.Graph.Categories))
}

func writeStrings(buf *bytes.Buffer, field string, values []string) {
	if len(values) == 0 {
		return
	}
	sorted := append([]string(nil), values...)
	sort.Strings(sorted)
	quoted := make([]string, 0, len(sorted))
	for _, value := range sorted {
		quoted = append(quoted, fmt.Sprintf("%q", value))
	}
	fmt.Fprintf(buf, "\t\t%s: []string{%s},\n", field, strings.Join(quoted, ", "))
}

func writeIdentifierSet(buf *bytes.Buffer, name, doc string, entries map[string]graphEntry) {
	fmt.Fprintf(buf, "// %s\nvar %s = map[string]string{\n", doc, name)
	for _, id := range sortedKeys(entries) {
		label := entries[id].Name
		if label == "" {
			label = entries[id].DisplayName
		}
		fmt.Fprintf(buf, "\t%q: %q,\n", id, label)
	}
	buf.WriteString("}\n\n")
}

func sortedKeys(entries map[string]graphEntry) []string {
	keys := make([]string, 0, len(entries))
	for key := range entries {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "apolloroleg:", err)
	os.Exit(1)
}
