// Command apolloroutegen emits the public Apollo API v0 route table from the
// pinned upstream OpenAPI snapshot.
//
// The adapter used to spell its thirteen routes by hand and a Ruby gate
// re-derived them from the snapshot to check they still agreed. That catches
// drift after the fact and only for the route set. Generating the table instead
// makes the snapshot the single source: a route that does not exist upstream
// cannot be registered, and a handler that loses its operation fails the
// generated-code diff rather than serving a path nobody pinned.
//
// It deliberately generates routes and nothing else. The request and response
// shapes stay hand-written, because the adapter answers with the platform's own
// types and the conformance tests pin those envelopes directly.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

type openAPIDocument struct {
	Paths map[string]map[string]struct {
		OperationID string `yaml:"operationId"`
	} `yaml:"paths"`
}

// httpMethods is the closed set this generator recognises. Anything else in the
// snapshot is a method the adapter has never served, and silently skipping it
// would hide a spec change behind an unchanged diff.
var httpMethods = map[string]string{
	"get": "GET", "post": "POST", "put": "PUT", "patch": "PATCH", "delete": "DELETE",
}

type route struct {
	Operation string
	Pattern   string
}

func main() {
	input := flag.String("input", "", "pinned Apollo OpenAPI snapshot")
	output := flag.String("output", "", "generated Go file")
	packageName := flag.String("package", "apollo", "generated Go package name")
	flag.Parse()
	if *input == "" || *output == "" {
		fmt.Fprintln(os.Stderr, "-input and -output are required")
		os.Exit(2)
	}
	contents, err := os.ReadFile(*input)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var document openAPIDocument
	if err := yaml.Unmarshal(contents, &document); err != nil {
		fmt.Fprintln(os.Stderr, "parse OpenAPI snapshot:", err)
		os.Exit(1)
	}
	routes, err := collectRoutes(document)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	rendered, err := render(*packageName, *input, routes)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*output, rendered, 0o600); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func collectRoutes(document openAPIDocument) ([]route, error) {
	if len(document.Paths) == 0 {
		return nil, fmt.Errorf("snapshot declares no paths")
	}
	routes := make([]route, 0, len(document.Paths))
	seen := map[string]string{}
	for path, item := range document.Paths {
		for method, operation := range item {
			verb, known := httpMethods[strings.ToLower(method)]
			if !known {
				continue
			}
			if strings.TrimSpace(operation.OperationID) == "" {
				return nil, fmt.Errorf("%s %s has no operationId to bind a handler to", verb, path)
			}
			if previous, exists := seen[operation.OperationID]; exists {
				return nil, fmt.Errorf("operationId %s is claimed by both %s and %s %s",
					operation.OperationID, previous, verb, path)
			}
			seen[operation.OperationID] = verb + " " + path
			// A Go 1.22 ServeMux wildcard is spelled exactly like an OpenAPI path
			// template, so the pattern is the pinned path verbatim. Anything that
			// needed rewriting here would be a route the snapshot does not describe.
			routes = append(routes, route{Operation: operation.OperationID, Pattern: verb + " " + path})
		}
	}
	sort.Slice(routes, func(i, j int) bool { return routes[i].Operation < routes[j].Operation })
	return routes, nil
}

// provenance names the snapshot by identity rather than by where it was read
// from. The directory carries the pinned upstream commit, which is the part
// worth recording; an absolute path would make the generated file differ
// between a local run and CI and break the regeneration diff.
func provenance(input string) string {
	cleaned := filepath.ToSlash(filepath.Clean(input))
	elements := strings.Split(cleaned, "/")
	if len(elements) >= 2 {
		return strings.Join(elements[len(elements)-2:], "/")
	}
	return cleaned
}

func render(packageName, source string, routes []route) ([]byte, error) {
	var buffer bytes.Buffer
	fmt.Fprintf(&buffer, "// Code generated by apolloroutegen from %s. DO NOT EDIT.\n\n", provenance(source))
	fmt.Fprintf(&buffer, "package %s\n\n", packageName)
	buffer.WriteString("// Route binds one pinned public operation to the pattern that serves\n")
	buffer.WriteString("// it. Both come from the snapshot; neither is chosen here.\n")
	buffer.WriteString("type Route struct {\n\tOperation string\n\tPattern   string\n}\n\n")
	buffer.WriteString("// Routes is every operation the pinned public contract declares.\n")
	buffer.WriteString("var Routes = []Route{\n")
	for _, item := range routes {
		fmt.Fprintf(&buffer, "\t{Operation: %q, Pattern: %q},\n", item.Operation, item.Pattern)
	}
	buffer.WriteString("}\n")
	formatted, err := format.Source(buffer.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated routes: %w", err)
	}
	return formatted, nil
}
